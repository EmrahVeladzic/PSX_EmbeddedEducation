{
    i &= 4095;
    if (i < 1024) {return  sin_quarter[i];}
    else if (i < 2048) {return  sin_quarter[2048 - i];}
    else if (i < 3072) {return -sin_quarter[i - 2048];}
    else {return -sin_quarter[4096 - i];}
}

